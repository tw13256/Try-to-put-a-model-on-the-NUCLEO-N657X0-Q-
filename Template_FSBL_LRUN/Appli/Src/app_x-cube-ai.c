void MX_X_CUBE_AI_Process(void)
{
    /* USER CODE BEGIN 6 */

    /* ============================================================= */
    /* 1. 變數宣告區                                                 */
    /* ============================================================= */
    LL_ATON_RT_RetValues_t ll_aton_rt_ret = LL_ATON_RT_DONE;

    // 緩衝區資訊
    const LL_Buffer_InfoTypeDef * ibuffersInfos;
    const LL_Buffer_InfoTypeDef * obuffersInfos;

    // 除錯用的地址 (根據 network.c 分析)
    // 這些是各層輸出的 "目的地"
    uint32_t sram5_base      = 0x342E0000;
    uint32_t raw_logits_addr = 0x342E0100; // Epoch 5 Output

    // 迴圈與計數變數
    int i, j;

    /* ============================================================= */
    /* 2. 系統初始化                                                 */
    /* ============================================================= */
    ibuffersInfos = NN_Interface_Default.input_buffers_info();
    obuffersInfos = NN_Interface_Default.output_buffers_info();

    buffer_in  = (uint8_t *)LL_Buffer_addr_start(&ibuffersInfos[0]);
    buffer_out = (uint8_t *)LL_Buffer_addr_start(&obuffersInfos[0]);

    buff_in_len = ibuffersInfos->offset_end - ibuffersInfos->offset_start;
    buff_out_len = obuffersInfos->offset_end - obuffersInfos->offset_start;

    printf("Debug: Input Size = %lu (Expected: 250)\n\r", buff_in_len);
    printf("Debug: Output Size = %lu (Expected: 2)\n\r", buff_out_len);

    static uint8_t srand_init = 0;
    if (!srand_init) {
        srand(HAL_GetTick());
        srand_init = 1;
    }

    LL_ATON_RT_RuntimeInit();
    Print_Security_Debug();

    printf("\r\n=============================================\r\n");
    printf("   STM32 NPU Debug: Layer-by-Layer Inspection\r\n");
    printf("=============================================\r\n");

    /* [Test 1] Flash 檢查 */
    uint8_t *flash_addr = (uint8_t *)0x71000000;
    printf("[Test 1] Checking Flash Header at 0x71000000...\r\n");
    printf("   Data: ");
    for(i=0; i<8; i++) printf("%02X ", flash_addr[i]);
    printf("\r\n");

    /* ============================================================= */
    /* 3. 推論迴圈                                                   */
    /* ============================================================= */
    // 使用 TEST_DATA_LEN 跑完所有測試資料
    for (i = 0; i < TEST_DATA_LEN; i++) {

        printf("\r\n--- [Sample #%d] ---\r\n", i);

        /* --- Step A: 填入輸入數據 --- */
        const int8_t *p_source_data = TEST_DATA_MIXED[i];
        for(uint32_t idx = 0; idx < buff_in_len; idx++){
            buffer_in[idx] = (uint8_t)p_source_data[idx];
        }

        // 印出輸入前 10 點 (確認輸入不同)
        printf("Input[0~9]: %d,%d,%d,%d,%d,%d,%d,%d,%d,%d \n\r",
                (int8_t)buffer_in[0], (int8_t)buffer_in[1], (int8_t)buffer_in[2],
                (int8_t)buffer_in[3], (int8_t)buffer_in[4], (int8_t)buffer_in[5],
                (int8_t)buffer_in[6], (int8_t)buffer_in[7], (int8_t)buffer_in[8],
                (int8_t)buffer_in[9]);

        /* --- Step B: 預填垃圾 (0x55) 到最終輸出區 --- */
        memset((void*)raw_logits_addr, 0x55, 32);
        mcu_cache_clean_invalidate_range(raw_logits_addr, 32);

        /* --- Step C: Cache 維護 --- */
        mcu_cache_clean_invalidate_range((uint32_t)buffer_in, (uint32_t)buff_in_len);
        npu_cache_invalidate();

        /* --- Step D: 執行推論 (含中間層監控) --- */
        printf(">>> Start Inference (Step-by-Step)...\n\r");
        LL_ATON_RT_Init_Network(&NN_Instance_Default);

        int epoch_step = 0; // 用來記錄現在跑到第幾層了

        do {
            /* 執行一個 Epoch Block */
            ll_aton_rt_ret = LL_ATON_RT_RunEpochBlock(&NN_Instance_Default);

            if (ll_aton_rt_ret == LL_ATON_RT_WFE) {
                LL_ATON_OSAL_WFE();
            }

            /* === [新功能] 中間層產出檢查 === */
            /* 每次 NPU 跑完一塊，我們就偷看一下 SRAM */
            epoch_step++;

            uint32_t inspect_addr = 0;
            char *step_name = "Unknown";

            // 根據 network.c 的記憶體規劃對應地址
            switch(epoch_step) {
                case 1: // Epoch 2 結束 (Conv2D -> MaxPool)
                    inspect_addr = 0x342E0100; // offset 256
                    step_name = "Ep2(MaxPool)";
                    break;
                case 2: // Epoch 3 結束 (Gemm)
                    inspect_addr = 0x342E1080; // offset 4224 (0x1080)
                    step_name = "Ep3(Gemm1)  ";
                    break;
                case 3: // Epoch 4 結束 (Gemm)
                    inspect_addr = 0x342E0000; // offset 0
                    step_name = "Ep4(Gemm2)  ";
                    break;
                case 4: // Epoch 5 結束 (Gemm -> Logits)
                    inspect_addr = 0x342E0100; // offset 256
                    step_name = "Ep5(Logits) ";
                    break;
                case 5: // Epoch 6 結束 (Softmax)
                    inspect_addr = 0x342E0110; // offset 272
                    step_name = "Ep6(Softmax)";
                    break;
                default:
                    inspect_addr = 0;
            }

            if (inspect_addr != 0) {
                // 刷新 Cache 確保讀到最新值
                mcu_cache_clean_invalidate_range(inspect_addr, 32);
                uint8_t *p_data = (uint8_t *)inspect_addr;

                printf("   [%s Output] @0x%08X: ", step_name, (unsigned int)inspect_addr);
                for(int k=0; k<10; k++) { // 印前10個 Byte
                    printf("%02X ", p_data[k]);
                }
                printf("\r\n");
            }
            /* ================================= */

        } while (ll_aton_rt_ret != LL_ATON_RT_DONE);

        /* --- Step E: 最終結果檢查 --- */
        if (ll_aton_rt_ret != LL_ATON_RT_DONE) {
            printf("Error: Inference failed, ret=%d\r\n", (int)ll_aton_rt_ret);
            continue;
        }

        // 讀取 Softmax 前的原始值 (Raw Logits)
        mcu_cache_clean_invalidate_range(raw_logits_addr, 32);
        int8_t *p_raw = (int8_t *)raw_logits_addr;

        // 讀取 Softmax 後的機率
        mcu_cache_clean_invalidate_range((uint32_t)buffer_out, (uint32_t)buff_out_len);
        int8_t raw_normal = (int8_t)buffer_out[0];
        int8_t raw_abnormal = (int8_t)buffer_out[1];

        // 顯示
        printf("   [Final Check]\r\n");
        printf("   ├── Raw Logits: [%d, %d]\r\n", p_raw[0], p_raw[1]);
        printf("   └── Final Prob: [%d, %d] -> ", raw_normal, raw_abnormal);

        if (raw_normal > raw_abnormal) {
            printf("Predict: NORMAL\r\n");
        } else {
            printf("Predict: ABNORMAL\r\n");
        }

        printf("--------------------------------------------------\r\n");

        LL_ATON_RT_DeInit_Network(&NN_Instance_Default);
    }

    LL_ATON_RT_RuntimeDeInit();
    /* USER CODE END 6 */
}
